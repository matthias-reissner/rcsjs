test("creates unified diffs for multiple changes and unterminated lines", () => {
  assert.equal(createUnifiedDiff("one\nsame\nold\n", "two\nsame\nnew\n", "old.txt", "new.txt"), [
    "--- old.txt",
    "+++ new.txt",
    "@@ -1,3 +1,3 @@",
    "-one",
    "+two",
    " same",
    "-old",
    "+new",
    "",
  ].join("\n"));
  assert.equal(createUnifiedDiff("old", "new"), [
    "--- a",
    "+++ b",
    "@@ -1,1 +1,1 @@",
    "-old",
    "\\ No newline at end of file",
    "+new",
    "\\ No newline at end of file",
    "",
  ].join("\n"));
  assert.equal(createUnifiedDiff("same\n", "same\n"), "");
  const before = Array.from({ length: 20 }, (_, index) => `line ${index + 1}\n`).join("");
  const after = before.replace("line 2\n", "changed 2\n").replace("line 18\n", "changed 18\n");
  const separated = createUnifiedDiff(before, after);
  assert.equal((separated.match(/^@@/gm) ?? []).length, 2);
  assert.doesNotMatch(separated, / line 10\n/);
});

test("unified diffs reproduce short text inputs", () => {
  const lineOptions = ["a\n", "b\n", "tail"];
  const texts = [""];
  for (const first of lineOptions) {
    texts.push(first);
    for (const second of lineOptions) {
      texts.push(first + second);
    }
  }

  for (const before of texts) {
    for (const after of texts) {
      const diff = createUnifiedDiff(before, after);
      if (!diff) {
        assert.equal(before, after);
        continue;
      }

      const output = [];
      let lastOutput = false;
      for (const line of diff.split("\n").slice(3)) {
        if (line === "\\ No newline at end of file") {
          if (lastOutput) {
            output[output.length - 1] = output[output.length - 1].slice(0, -1);
          }
          continue;
        }
        if (line.startsWith("+") || line.startsWith(" ")) {
          output.push(`${line.slice(1)}\n`);
          lastOutput = true;
        } else {
          lastOutput = false;
        }
      }
      assert.equal(output.join(""), after, `diff did not reconstruct ${JSON.stringify(after)}`);
    }
  }
});

test("three-way merge combines separate edits and marks overlapping changes", () => {
  const base = "one\ntwo\nthree\n";
  const clean = mergeThreeWay(base, "ONE\ntwo\nthree\n", "one\ntwo\nTHREE\n");
  assert.deepEqual(clean, { content: "ONE\ntwo\nTHREE\n", conflicts: 0 });

  const same = mergeThreeWay(base, "one\nTWO\nthree\n", "one\nTWO\nthree\n");
  assert.deepEqual(same, { content: "one\nTWO\nthree\n", conflicts: 0 });

  const conflict = mergeThreeWay(base, "one\nlocal\nthree\n", "one\nincoming\nthree\n");
  assert.deepEqual(conflict, {
    content: "one\n<<<<<<< local\nlocal\n=======\nincoming\n>>>>>>> incoming\nthree\n",
    conflicts: 1,
  });
});

test("handles merge boundaries, identical edits, and competing insertions", () => {
  const adjacent = mergeThreeWay(
    "a\nb\nc\n",
    "a\nlocal\nb\nc\n",
    "a\nb\nincoming\nc\n",
  );
  assert.deepEqual(adjacent, {
    content: "a\nlocal\nb\nincoming\nc\n",
    conflicts: 0,
  });

  const identical = mergeThreeWay("a\nb\nc\n", "a\nsame\nc\n", "a\nsame\nc\n");
  assert.deepEqual(identical, { content: "a\nsame\nc\n", conflicts: 0 });

  const inserted = mergeThreeWay("a\nb\n", "a\nlocal\nb\n", "a\nincoming\nb\n");
  assert.equal(inserted.conflicts, 1);
  assert.match(inserted.content, /<<<<<<< local\nlocal\n=======\nincoming\n>>>>>>> incoming/);

  const deletedAndChanged = mergeThreeWay("a\nb\nc\n", "a\nc\n", "a\nchanged\nc\n");
  assert.equal(deletedAndChanged.conflicts, 1);
  assert.match(deletedAndChanged.content, /<<<<<<< local\n=======\nchanged\n>>>>>>> incoming/);
});

