test("reads and writes RCS archives through the Node.js adapter", async () => {
  const directory = await mkdtemp(join(tmpdir(), "rcsjs-"));
  const archivePath = join(directory, "example,v");
  let archiveReadOnly = false;

  try {
    const archive = checkin(createArchive({ description: "File-backed archive" }), "content\n", {
      author: "alice",
      date: new Date("2024-01-01T00:00:00Z"),
    });
    await writeArchiveFile(archivePath, archive);

    const restored = await readArchiveFile(archivePath);
    assert.equal(restored.description, "File-backed archive");
    assert.equal(checkout(restored), "content\n");

    const updated = checkin(restored, "updated\n", {
      author: "alice",
      date: new Date("2024-01-02T00:00:00Z"),
    });
    await writeArchiveFile(archivePath, updated);
    await chmod(archivePath, 0o444);
    archiveReadOnly = true;
    await writeArchiveFile(archivePath, archive);
    await chmod(archivePath, 0o666);
    archiveReadOnly = false;

    await assert.rejects(writeArchiveFile(archivePath, { revisions: "invalid" }), /archive object/);
    const replaced = await readArchiveFile(archivePath);
    assert.equal(checkout(replaced), "content\n");
  } finally {
    if (archiveReadOnly) {
      await chmod(archivePath, 0o666);
    }
    await rm(directory, { recursive: true, force: true });
  }
});

