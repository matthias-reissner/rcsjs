test("enforces strict locks and releases the check-in lock", () => {
  let archive = checkin(createArchive(), "first\n", {
    author: "alice",
    date: new Date("2024-01-01T00:00:00Z"),
  });
  archive = setStrictLocking(archive, true);

  assert.throws(
    () => checkin(archive, "second\n", { author: "alice" }),
    /Strict locking requires alice to lock revision 1.1/,
  );
  archive = lockRevision(archive, "alice", "1.1");
  assert.throws(() => lockRevision(archive, "bob", "1.1"), /already locked by alice/);
  assert.throws(() => checkin(archive, "second\n", { author: "bob" }), /Strict locking requires/);

  archive = checkin(archive, "first\n", { author: "alice" });
  assert.equal(archive.head, "1.1");
  assert.deepEqual(archive.locks, {});
  archive = lockRevision(archive, "alice", "1.1");

  archive = checkin(archive, "second\n", {
    author: "alice",
    date: new Date("2024-01-02T00:00:00Z"),
  });
  assert.equal(archive.head, "1.2");
  assert.deepEqual(archive.locks, {});

  archive = lockRevision(archive, "alice", "1.2");
  archive = lockRevision(archive, "bob", "1.2", { force: true });
  assert.throws(() => unlockRevision(archive, "alice", "1.2"), /does not hold a lock/);
  archive = unlockRevision(archive, "bob", "1.2");
  assert.deepEqual(archive.locks, {});

  archive = lockRevision(archive, "alice", "1.1");
  archive = checkin(archive, "branch\n", {
    author: "alice",
    branch: "1.1.2",
    date: new Date("2024-01-03T00:00:00Z"),
  });
  assert.equal(checkout(archive, "1.1.2"), "branch\n");
  assert.deepEqual(archive.locks, {});
});

